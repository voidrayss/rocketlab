import assert from 'node:assert/strict';
import {defaultRocket,layoutPositions,totalLength,createBody} from '../js/rocket.js';
import {resolveAssembly,defaultAttachment} from '../js/assembly.js';
import {addComponent,editComponent,deleteComponent,duplicateComponent} from '../js/components.js';
import {massProperties,centerOfPressure,wettedArea} from '../js/aero.js';
import {parseProject,serializeProject,parsePart,serializePart} from '../js/project.js';
const rocket=defaultRocket(),body=rocket.components.find(c=>c.type==='body');
editComponent(rocket,body.id,{length:.7,diameter:.08});
assert.equal(rocket.components[0].diameter,.08);
const oldNose=rocket.components[0];deleteComponent(rocket,oldNose.id);
const nose=addComponent(rocket,'nose');assert.equal(nose.diameter,.08);assert.notEqual(nose.uid,oldNose.uid);assert.equal(layoutPositions(rocket).get(nose.id),0);
const wettedBefore=wettedArea(rocket);
const can=addComponent(rocket,'finCan');
assert(Math.abs(wettedArea(rocket)-(wettedBefore-Math.PI*.08*can.length+Math.PI*can.diameter*can.length))<1e-12);
assert.equal(can.attachment.parentId,body.id);assert(Math.abs(can.innerDiameter-.0804)<1e-12);
assert(Math.abs(totalLength(rocket)-.85)<1e-12);assert(Math.abs(layoutPositions(rocket).get(can.id)-.73)<1e-12);
editComponent(rocket,body.id,{length:.9,diameter:.09});assert(Math.abs(layoutPositions(rocket).get(can.id)-.93)<1e-12);assert(Math.abs(can.innerDiameter-.0904)<1e-12);
assert.throws(()=>editComponent(rocket,can.id,{diameter:.1}));
editComponent(rocket,can.id,{attachment:{...can.attachment,fit:'inside'}});
assert(Math.abs(can.diameter-(.09-.002-.0004))<1e-12);
editComponent(rocket,can.id,{attachment:{...can.attachment,matching:'locked'}});
const locked=can.diameter;editComponent(rocket,body.id,{diameter:.1});assert.equal(can.diameter,locked);
const mass=massProperties(rocket).mass,cp=centerOfPressure(rocket).cp;
editComponent(rocket,body.id,{visible:false});assert.equal(massProperties(rocket).mass,mass);
const duplicate=duplicateComponent(rocket,can.id);assert.equal(duplicate.inAssembly,false);assert.notEqual(duplicate.uid,can.uid);assert.equal(massProperties(rocket).mass,mass);assert.equal(centerOfPressure(rocket).cp,cp);
const restored=parseProject(serializeProject(rocket));const restoredBody=restored.components.find(c=>c.uid===body.uid),restoredNose=restored.components.find(c=>c.uid===nose.uid);
assert.notEqual(restoredBody.id,body.id);assert.equal(restoredNose.attachment.parentId,restoredBody.id);
assert.equal(massProperties(restored).cg,massProperties(rocket).cg);
const part=parsePart(serializePart(can));assert.equal(part.attachment,undefined);assert.equal(part.inAssembly,false);assert.notEqual(part.uid,can.uid);
const other=createBody();const cycle={components:[{...body,attachment:defaultAttachment(other.id,'body')},{...other,attachment:defaultAttachment(body.id,'body')}]};assert.throws(()=>resolveAssembly(cycle),/Circular/);
const before=JSON.stringify(rocket);assert.throws(()=>editComponent(rocket,body.id,{diameter:.0001}));assert.equal(JSON.stringify(rocket),before);
deleteComponent(rocket,can.id);const newCan=addComponent(rocket,'finCan',body.id);assert(Math.abs(newCan.innerDiameter-(body.diameter+.0004))<1e-12);
deleteComponent(rocket,body.id);assert(rocket.components.find(c=>c.uid===nose.uid).inAssembly===false);
console.log('PASS: resizing/attachments, recreation, fits, locked sizes, cycles, library isolation, identities and part/project files');
