import assert from 'node:assert/strict';
import {createRing,defaultRocket,totalLength,layoutPositions} from '../js/rocket.js';
import {ringProperties} from '../js/rings.js';
import {massProperties,centerOfPressure,referenceArea,dragCoefficient,wettedArea} from '../js/aero.js';
import {massBreakdown} from '../js/analysis.js';
import {serializeProject,parseProject} from '../js/project.js';
const ring=createRing();const p=ringProperties(ring);
const exact=Math.PI*(.048**2-.029**2)*.005/4;
assert.equal(p.volume,exact);
assert.equal(massProperties({components:[ring]}).mass,exact*600);
assert.equal(massProperties({components:[ring]}).cg,.4025);
const r=defaultRocket(),mass=massProperties(r).mass,cp=centerOfPressure(r).cp,area=referenceArea(r),cd=dragCoefficient(r),sw=wettedArea(r);
r.components.push(ring);
assert.equal(totalLength(r),.5);assert.equal(layoutPositions(r).get(ring.id),.4);
assert.equal(centerOfPressure(r).cp,cp);assert.equal(referenceArea(r),area);assert.equal(dragCoefficient(r),cd);assert.equal(wettedArea(r),sw);
assert(Math.abs(massProperties(r).mass-mass-exact*600)<1e-12);
assert(Math.abs(massBreakdown(r).at(-1).grams-exact*600*1000)<1e-12);
const restored=parseProject(serializeProject(r));assert.equal(restored.components.at(-1).type,'ring');assert.equal(massProperties(restored).cg,massProperties(r).cg);
for(const bad of [{innerDiameter:.05},{length:0},{axialOffset:-1},{diameter:NaN}])assert.throws(()=>createRing(bad));
console.log('PASS: internal ring volume/mass/CG, placement, no aero duplication, project round trip and invalid inputs');
