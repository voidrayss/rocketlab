// Synthetic cube asset tests schema/placement; real STEP topology is covered by cad-check/browser-check.
import assert from 'node:assert/strict';
import { createImported, defaultRocket, layoutPositions, totalLength } from '../js/rocket.js';
import { bytesToBase64, base64ToBytes, stepHash, metadataComparison, importedPoint, PROJECT_LIMIT, verifyProjectAssets } from '../js/imported.js';
import { massProperties, referenceArea, centerOfPressure } from '../js/aero.js';
import { massBreakdown } from '../js/analysis.js';
import { serializeProject, parseProject } from '../js/project.js';
const bytes=new TextEncoder().encode('ISO-10303-21;\nsynthetic schema-test placeholder');
const cad={stepBase64:bytesToBase64(bytes),sha256:await stepHash(bytes),properties:{valid:true,solids:1,volumeMm3:1000,centroidMm:[5,5,5],boundsMm:[[0,0,0],[10,10,10]]},mesh:{positions:[0,0,0,10,0,0,0,10,10],indices:[0,1,2]},metadata:null};
assert.deepEqual(base64ToBytes(cad.stepBase64),bytes);
const c=createImported({cad,name:'Cube',material:'aluminum',density:2700,axialOffset:.2});
assert(Math.abs(massProperties({components:[c]}).mass-.0027)<1e-12);
assert(Math.abs(massProperties({components:[c]}).cg-.205)<1e-12);
const rotated={...c,rotationX:180};
assert(Math.abs(massProperties({components:[rotated]}).cg-.195)<1e-12);
const r=defaultRocket(),baseMass=massProperties(r).mass,baseCg=massProperties(r).cg,baseCp=centerOfPressure(r).cp;
r.components.push(c);
assert.equal(totalLength(r),.5);assert.equal(centerOfPressure(r).cp,baseCp);
assert(Math.abs(massProperties(r).cg-(baseMass*baseCg+.0027*.205)/(baseMass+.0027))<1e-12);
assert(Math.abs(massBreakdown(r).at(-1).grams-2.7)<1e-12);
const external=createImported({...c,aeroRole:'body',length:.1,diameter:.08,axialOffset:.01});
const ext={...r,components:[...r.components.slice(0,2),external]};
assert.equal(totalLength(ext),.61);assert.equal(layoutPositions(ext).get(external.id),.51);
assert(Math.abs(referenceArea(ext)-Math.PI*.04**2)<1e-12);
const text=serializeProject(r);assert.equal(JSON.parse(text).version,3);
const restored=parseProject(text),loaded=restored.components.at(-1);
assert.notEqual(loaded.id,c.id);assert.deepEqual(loaded.cad,c.cad);assert.equal(loaded.density,2700);
assert.equal(massProperties(restored).cg,massProperties(r).cg);
await verifyProjectAssets(restored);
await assert.rejects(()=>verifyProjectAssets({...restored,components:[{...loaded,cad:{...cad,sha256:'0'.repeat(64)}}]}));
const meta={format:'rocketlab-cad',version:2,stepSha256:cad.sha256,component:{type:'body'},properties:cad.properties};
assert(metadataComparison(meta,{sha256:cad.sha256,properties:cad.properties}).canRestore);
assert(!metadataComparison({...meta,stepSha256:'0'.repeat(64)},{sha256:cad.sha256,properties:cad.properties}).canRestore);
assert(!metadataComparison({...meta,version:1},{sha256:cad.sha256,properties:cad.properties}).canRestore);
assert(!metadataComparison(meta,{sha256:cad.sha256,properties:{...cad.properties,volumeMm3:2000}}).propertiesMatch);
for(const mutation of [{density:-1},{rotationY:Infinity},{aeroRole:'automatic'},{cad:{...cad,stepBase64:'bad'}},{cad:{...cad,mesh:{positions:[NaN],indices:[]}}}])assert.throws(()=>createImported({...c,...mutation}));
assert.throws(()=>parseProject(' '.repeat(PROJECT_LIMIT+1)));
assert.deepEqual(importedPoint(c,[5,5,5]),[.005,0,0]);
console.log('PASS: imported CAD mass/CG, transformations, aerodynamic role, source/metadata persistence, guarded restoration and invalid inputs');
