import assert from 'node:assert/strict';
import {createFinCan,createBody,createNose,totalLength,bodyLength,layoutPositions,overallBounds} from '../js/rocket.js';
import {finCanProperties} from '../js/fincan.js';
import {centerOfPressure,massProperties} from '../js/aero.js';
import {serializeProject,parseProject} from '../js/project.js';
const c=createFinCan({finOffset:.08,rootChord:.12,tipChord:.08,sweep:.05});
const rocket={name:'Overhang',motorId:'C6',components:[createNose(),createBody(),c]};
assert(Math.abs(bodyLength(rocket)-.57)<1e-12);assert(Math.abs(totalLength(rocket)-.66)<1e-12);
const props=finCanProperties(c);assert(Math.abs(props.supportFraction-1/3)<1e-12);
assert(props.centroidX>0&&props.centroidX<.21);assert(Number.isFinite(centerOfPressure(rocket).cp));
const shifted={...rocket,components:[...rocket.components.slice(0,2),{...c,finOffset:0}]};
assert(centerOfPressure(rocket).cp>centerOfPressure(shifted).cp);
assert(massProperties(rocket).cg>massProperties(shifted).cg);
const restored=parseProject(serializeProject(rocket));assert.equal(restored.components.at(-1).finOffset,.08);assert.equal(totalLength(restored),totalLength(rocket));
const forward=createFinCan({finOffset:-.08,rootChord:.2,tipChord:.12,sweep:-.05});
const isolated={components:[forward]};assert(overallBounds(isolated).min<0);assert(totalLength(isolated)>bodyLength(isolated));
assert(Math.abs(layoutPositions(rocket).get(c.id)-.45)<1e-12);
assert.throws(()=>createFinCan({finOffset:.12}),/disconnected/);
assert.throws(()=>createFinCan({finOffset:-.2,rootChord:.1}),/disconnected/);
assert.throws(()=>createFinCan({finOffset:NaN}));
console.log('PASS: positive/negative overhang, supported root mass/CG, CP and overall bounds, disconnected rejection and project persistence');
