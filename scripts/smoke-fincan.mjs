import assert from 'node:assert/strict';
import { createFinCan, createBody, createNose, createFins, defaultRocket, totalLength, layoutPositions, MATERIALS } from '../js/rocket.js';
import { finCanProperties } from '../js/fincan.js';
import { massProperties, centerOfPressure, stabilityMargin, dragCoefficient, flutterVelocity } from '../js/aero.js';
import { massBreakdown, buildReport } from '../js/analysis.js';
import { serializeProject, parseProject } from '../js/project.js';
import { getMotor } from '../js/motors.js';
const c = createFinCan();
const r = { name: 'Fin can test', motorId: 'C6', components: [createNose(), createBody(), c] };
const p = finCanProperties(c);
assert(p.volume > p.sleeveVolume && p.centroidX > 0 && p.centroidX < c.length);
const single = { components: [c] };
assert.equal(massProperties(single).mass, p.volume * MATERIALS.plastic);
assert.equal(massProperties(single).cg, p.centroidX);
assert.equal(totalLength(r), .15 + .3 + .12);
assert.equal(layoutPositions(r).get(c.id), .15 + .3);
const equiv = { ...r, components: [...r.components.slice(0,2), createBody({length:c.length}), createFins(c)] };
assert(Math.abs(centerOfPressure(r).cp - centerOfPressure(equiv).cp) < 1e-12);
assert(Math.abs(dragCoefficient(r) - dragCoefficient(equiv)) < 1e-12);
assert.equal(massBreakdown(single)[0].grams, massProperties(single).mass * 1000);
assert(Number.isFinite(stabilityMargin(r, .0258).calibers));
assert(Number.isFinite(flutterVelocity(r).velocity));
assert.equal(parseProject(serializeProject(r)).components.at(-1).innerDiameter, c.innerDiameter);
assert(buildReport(r, getMotor('C6')).metrics.every(m => typeof m.value !== 'number' || Number.isFinite(m.value)));
for (const bad of [{innerDiameter: .06}, {count: 1}, {thickness: .05}, {rootChord: .2}, {sweep: -.01}, {span: NaN}]) assert.throws(() => createFinCan(bad));
assert.throws(() => serializeProject({...r, components:[...r.components,createFins()]}));
assert.equal(defaultRocket().components.length, 3);
console.log('PASS: fin-can mass/CG, single aerodynamic fin set, placement, validation, project round trip');
