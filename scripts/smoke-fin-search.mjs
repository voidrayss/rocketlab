import assert from 'node:assert/strict';
import {defaultRocket,createFinCan,createNose,createBody,bodyLength} from '../js/rocket.js';
import {finAngles,anglePatch,planformPatch,PLANFORMS} from '../js/fins.js';
import {searchFins} from '../js/optimize.js';
import {getMotor} from '../js/motors.js';
import {stabilityMargin} from '../js/aero.js';
import {serializeProject,parseProject} from '../js/project.js';
const c=createFinCan(),leading={...c,...anglePatch(c,'leading',30)};
assert(Math.abs(finAngles(leading).leading-30)<1e-12);
const trailing={...leading,...anglePatch(leading,'trailing',0)};assert(Math.abs(finAngles(trailing).trailing)<1e-12);
assert.equal(trailing.rootChord,c.rootChord);assert.equal(trailing.span,c.span);
assert.throws(()=>anglePatch(c,'leading',90));assert.throws(()=>anglePatch({...c,sweep:1},'trailing',0));
const rect={...c,...planformPatch(c,'rectangular')};assert.equal(rect.tipChord,rect.rootChord);assert.equal(rect.sweep,0);
for(const planform of PLANFORMS){const part=createFinCan({...c,...planformPatch(c,planform)});assert.equal(part.crossSection,'flat');}
assert.throws(()=>createFinCan({crossSection:'airfoil'}));assert.throws(()=>createFinCan({planform:'elliptical'}));
const rocket=defaultRocket(),fin=rocket.components.find(c=>c.type==='fins'),motor=getMotor('C6');
const before=JSON.stringify(rocket),options={minMargin:.5,maxMargin:3,maxMassKg:.1};
const result=searchFins(rocket,fin.id,motor,options),again=searchFins(rocket,fin.id,motor,options);
assert.deepEqual(result,again);assert(result.best&&result.feasible>0&&result.evaluated>result.feasible);assert.equal(JSON.stringify(rocket),before);
const candidate={...rocket,components:rocket.components.map(c=>c.id===fin.id?{...c,...result.best.patch}:c)};
const margin=stabilityMargin(candidate,motor.totalMass,bodyLength(candidate)-.05).calibers;
assert.equal(margin,result.best.margin);assert(margin>=.5&&margin<=3);assert(result.best.massKg<=.1);
assert(searchFins(rocket,fin.id,motor,{...options,objective:'stability'}).best);
assert.equal(searchFins(rocket,fin.id,motor,{...options,maxMassKg:1e-9}).best,null);
assert.throws(()=>searchFins(rocket,fin.id,motor,{objective:'structural'}));
assert.throws(()=>searchFins(rocket,fin.id,motor,{maxSpan:-1}));
const canRocket={name:'Search can',motorId:'C6',components:[createNose(),createBody(),c]};assert(searchFins(canRocket,c.id,motor,{minMargin:0,maxMargin:10,maxMassKg:.5}).best);
const restored=parseProject(serializeProject(candidate));assert.equal(restored.components.find(c=>c.type==='fins').planform,'custom');
console.log('PASS: consistent fin angles, supported presets, cross-section guards, deterministic constrained search, no mutation and persistence');
